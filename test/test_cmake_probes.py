#!/usr/bin/env python3
"""Run cmake semantics probes and verify File API output.

Each probe is a small cmake program (generated by probes.exe) with
assertions on the cmake File API JSON output. This empirically verifies
our understanding of cmake's string/target/file semantics.

Usage: python3 test/test_cmake_probes.py [probe_name ...]
  Run from project root. If no names given, runs all probes.
"""

import json, glob, os, shutil, subprocess, sys, tempfile

PROBES_EXE = "_build/default/test/test-cmake-semantics/probes.exe"


# ---- File API helpers (from cmake_file_api_cmp.py) ----

def run_cmake(source_dir, build_dir):
    """Run cmake configure with File API query. Returns (success, stderr)."""
    query = os.path.join(build_dir, ".cmake", "api", "v1", "query")
    os.makedirs(query, exist_ok=True)
    open(os.path.join(query, "codemodel-v2"), "w").close()
    open(os.path.join(query, "cache-v2"), "w").close()
    r = subprocess.run(
        ["cmake", "-S", source_dir, "-B", build_dir],
        capture_output=True, text=True,
    )
    return r.returncode == 0, r.stderr


def strip_unstable(obj):
    """Strip fields that vary between runs."""
    if isinstance(obj, dict):
        return {
            k: strip_unstable(v)
            for k, v in obj.items()
            if k not in ("jsonFile", "backtrace", "backtraceGraph")
        }
    if isinstance(obj, list):
        return [strip_unstable(v) for v in obj]
    return obj


def load_replies(build_dir):
    reply_dir = os.path.join(build_dir, ".cmake", "api", "v1", "reply")
    if not os.path.isdir(reply_dir):
        return {}
    results = {}
    for pattern in ["codemodel-v2", "cache-v2", "target-*"]:
        files = glob.glob(os.path.join(reply_dir, f"{pattern}*.json"))
        for f in files:
            basename = os.path.basename(f)
            key = basename.rsplit("-", 1)[0]
            with open(f) as fh:
                results[key] = strip_unstable(json.load(fh))
    return results


def get_targets(replies):
    """Extract {name: target_json} from File API replies."""
    targets = {}
    for key, val in replies.items():
        if key.startswith("target-"):
            name = val.get("name", key)
            targets[name] = val
    return targets


def get_cache_entries(replies):
    """Extract {name: {type, value}} from cache reply."""
    cache = replies.get("cache-v2", {})
    entries = {}
    for e in cache.get("entries", []):
        entries[e["name"]] = {"type": e.get("type"), "value": e.get("value")}
    return entries


# ---- Probe runner ----

def get_probe_list():
    r = subprocess.run([PROBES_EXE, "--list"], capture_output=True, text=True)
    return r.stdout.strip().split("\n")


def get_probe_cmake(name):
    r = subprocess.run([PROBES_EXE, name], capture_output=True, text=True)
    return r.stdout


def get_probe_sources(name):
    r = subprocess.run([PROBES_EXE, name, "--sources"], capture_output=True, text=True)
    return [s for s in r.stdout.strip().split("\n") if s]


def get_probe_subdirs(name):
    r = subprocess.run([PROBES_EXE, name, "--subdirs"], capture_output=True, text=True)
    return [s for s in r.stdout.strip().split("\n") if s]


def get_probe_subdir_cmake(name, subdir):
    r = subprocess.run([PROBES_EXE, name, "--subdir", subdir], capture_output=True, text=True)
    return r.stdout


def get_probe_subdir_sources(name, subdir):
    r = subprocess.run([PROBES_EXE, name, "--subdir-sources", subdir], capture_output=True, text=True)
    return [s for s in r.stdout.strip().split("\n") if s]


def setup_probe_project(name, tmpdir):
    """Create a cmake project directory for the probe."""
    src = os.path.join(tmpdir, "src")
    os.makedirs(src)

    # Write root CMakeLists.txt
    with open(os.path.join(src, "CMakeLists.txt"), "w") as f:
        f.write(get_probe_cmake(name))

    # Create dummy source files
    for s in get_probe_sources(name):
        path = os.path.join(src, s)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            if s.endswith(".c") or s.endswith(".cxx") or s.endswith(".cpp"):
                f.write("/* dummy */\n")
            elif s.endswith(".h.in"):
                f.write("/* config template */\n")
            else:
                f.write("")

    # Create subdirectories
    for subdir in get_probe_subdirs(name):
        subdir_path = os.path.join(src, subdir)
        os.makedirs(subdir_path, exist_ok=True)
        with open(os.path.join(subdir_path, "CMakeLists.txt"), "w") as f:
            f.write(get_probe_subdir_cmake(name, subdir))
        for s in get_probe_subdir_sources(name, subdir):
            path = os.path.join(subdir_path, s)
            with open(path, "w") as f:
                f.write("/* dummy */\n")

    return src


