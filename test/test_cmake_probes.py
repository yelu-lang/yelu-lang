def check_probe(name, verbose=False):
    """Run one probe, return (passed, errors)."""
    expect = EXPECTATIONS.get(name)
    if expect is None:
        return False, [f"no expectations defined for '{name}'"]

    errors = []
    with tempfile.TemporaryDirectory(prefix=f"cmake_probe_{name}_") as tmpdir:
        src = setup_probe_project(name, tmpdir)
        build = os.path.join(tmpdir, "build")

        success, stderr = run_cmake(src, build)

        # Check success/failure
        if expect.get("expect_success", True):
            if not success:
                errors.append(f"cmake configure failed (expected success)\n{stderr}")
                return False, errors
        else:
            if success:
                errors.append("cmake configure succeeded (expected failure)")
            return len(errors) == 0, errors

        replies = load_replies(build)
        targets = get_targets(replies)
        cache = get_cache_entries(replies)

        # Check target count
        if "target_count" in expect:
            if len(targets) != expect["target_count"]:
                errors.append(
                    f"target_count: expected {expect['target_count']}, got {len(targets)} "
                    f"({list(targets.keys())})"
                )

        # Check specific targets
        if "targets" in expect:
            for tname, texpect in expect["targets"].items():
                if tname not in targets:
                    errors.append(f"target '{tname}' not found (have: {list(targets.keys())})")
                    continue
                t = targets[tname]
                if "type" in texpect and t.get("type") != texpect["type"]:
                    errors.append(
                        f"target '{tname}' type: expected {texpect['type']}, got {t.get('type')}"
                    )

        # Check targets that should NOT exist
        if "target_absent" in expect:
            for tname in expect["target_absent"]:
                if tname in targets:
                    errors.append(f"target '{tname}' should NOT exist but found")

        # Check link dependency
        if "check_link" in expect:
            from_t, to_t = expect["check_link"]
            if from_t in targets:
                t = targets[from_t]
                deps = []
                for cg in t.get("compileGroups", []):
                    pass
                # Check dependencies field
                found_dep = False
                for dep in t.get("dependencies", []):
                    dep_id = dep.get("id", "")
                    # dependency id format: "target_name::hash"
                    if to_t in dep_id:
                        found_dep = True
                        break
                if not found_dep:
                    errors.append(
                        f"target '{from_t}' should depend on '{to_t}' but dependency not found"
                    )

        # Check compile definition
        if "check_define" in expect:
            tname, define = expect["check_define"]
            if tname in targets:
                t = targets[tname]
                found = False
                for cg in t.get("compileGroups", []):
                    for d in cg.get("defines", []):
                        if d.get("define", "").startswith(define):
                            found = True
                            break
                if not found:
                    errors.append(
                        f"target '{tname}' should have define '{define}' but not found in compileGroups"
                    )

        # Check cache entries
        if "cache_has" in expect:
            for cname, cval in expect["cache_has"].items():
                if cname not in cache:
                    errors.append(f"cache variable '{cname}' not found")
                elif cache[cname]["value"] != cval:
                    errors.append(
                        f"cache '{cname}': expected value '{cval}', got '{cache[cname]['value']}'"
                    )

        # Check cache absent
        if "cache_absent" in expect:
            for cname in expect["cache_absent"]:
                if cname in cache:
                    errors.append(f"cache variable '{cname}' should NOT exist but found")

        if "cache_type" in expect:
            for cname, ctype in expect["cache_type"].items():
                if cname in cache and cache[cname]["type"] != ctype:
                    errors.append(
                        f"cache '{cname}': expected type '{ctype}', got '{cache[cname]['type']}'"
                    )

        if verbose and not errors:
            note = expect.get("note", "")
            if note:
                print(f"    confirmed: {note}")

    return len(errors) == 0, errors


def main():
    # Build probes first
    r = subprocess.run(
        ["dune", "build", "test/test-cmake-semantics/"],
        capture_output=True, text=True,
    )
    if r.returncode != 0:
        print("dune build failed:")
        print(r.stderr)
        sys.exit(2)

    # Get probe list
    if len(sys.argv) > 1:
        probes = sys.argv[1:]
    else:
        probes = get_probe_list()

    passed = 0
    failed = 0
    print("--- cmake semantics probes ---")
    for name in probes:
        ok, errors = check_probe(name, verbose=True)
        if ok:
            print(f"  {name}: PASS")
            passed += 1
        else:
            print(f"  {name}: FAIL")
            for e in errors:
                print(f"    {e}")
            failed += 1

    print(f"\nPassed: {passed}, Failed: {failed}")
    sys.exit(0 if failed == 0 else 1)


if __name__ == "__main__":
    main()
